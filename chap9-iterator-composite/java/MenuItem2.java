/**
 * Leaf of the Composite pattern: a single menu item; it does not support add/remove/getChild.
 */
public class MenuItem2 extends MenuComponent {
    String name;
    String description;
    boolean vegetarian;
    double price;

    public MenuItem2(String name, String description, boolean vegetarian, double price) {
        this.name = name;
        this.description = description;
        this.vegetarian = vegetarian;
        this.price = price;
    }

    public String getName() {
        return name;
    }

    public String getDescription() {
        return description;
    }

    public double getPrice() {
        return price;
    }

    public boolean isVegetarian() {
        return vegetarian;
    }

    // Leaf behavior: prints itself, with (v) for vegetarian items.
    public void print() {
        System.out.print(" " + getName());
        if (isVegetarian()) {
            System.out.print("(v)");
        }
        System.out.println(", " + getPrice());
        System.out.println("    -- " + getDescription());
    }
}
