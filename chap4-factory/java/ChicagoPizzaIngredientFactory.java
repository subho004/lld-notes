/**
 * Concrete Abstract Factory for the Chicago family (thick crust, plum tomato, mozzarella, frozen clams).
 */
public class ChicagoPizzaIngredientFactory implements IngredientFactory {
    public Dough createDough() {
        return new ThickCrustDough();
    }

    public Sauce createSauce() {
        return new PlumTomatoSauce();
    }

    public Cheese createCheese() {
        return new MozzarellaCheese();
    }

    public Veggies[] createVeggies() {
        return new Veggies[] { new Spinach(), new Eggplant(), new BlackOlives() };
    }

    public Pepperoni createPepperoni() {
        return new SlicedPepperoni();
    }

    public Clams createClam() {
        return new FrozenClams();
    }
}
